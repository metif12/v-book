module main

import strings

// SearchDoc is one document in the client side search index.
//
// A page is split into one document per section, so a match deep in a chapter
// links to that heading rather than to the top of the chapter.
pub struct SearchDoc {
	title string
	url   string
	text  string
	part  string
}

// build_search_docs splits one page's Markdown into searchable documents: the
// page itself, then one document per heading inside it.
pub fn build_search_docs(page_title string, page_url string, part string, markdown string) []SearchDoc {
	mut docs := []SearchDoc{}
	headings, bodies := split_sections(markdown)
	for i, heading in headings {
		text := clean_doc_text(bodies[i])
		if text == '' {
			continue
		}
		docs << SearchDoc{
			title: if heading == '' { page_title } else { '${page_title} · ${heading}' }
			url:   page_url
			text:  text
			part:  part
		}
	}
	return docs
}

// split_sections groups Markdown lines under the heading they follow.
//
// The heading list and the body list stay the same length, and an empty heading
// marks the prose that comes before the first heading of the page.
fn split_sections(markdown string) ([]string, []string) {
	mut headings := ['']
	mut bodies := []string{}
	mut body := []string{}
	mut in_code := false
	for line in markdown.replace('\r\n', '\n').split('\n') {
		t := line.trim_space()
		if t.starts_with('```') {
			in_code = !in_code
			continue
		}
		if in_code {
			if t != '' {
				body << t
			}
			continue
		}
		if t.starts_with('#') {
			mut level := 0
			for level < t.len && t[level] == `#` {
				level++
			}
			heading := t[level..].trim_space()
			if level >= 2 && heading != '' {
				headings << strip_inline_marks(heading)
				bodies << body.join(' ')
				body = []string{}
				continue
			}
			body << strip_inline_marks(heading)
			continue
		}
		if t == '' || t == '---' {
			continue
		}
		body << strip_inline_marks(t)
	}
	bodies << body.join(' ')
	return headings, bodies
}

// clean_doc_text collapses the whitespace a slice of Markdown lines carries.
fn clean_doc_text(s string) string {
	return s.replace('\t', ' ').trim_space()
}

// strip_inline_marks removes Markdown emphasis markers, which would otherwise
// sit between the letters of a word a reader searches for.
fn strip_inline_marks(s string) string {
	// A link wrapped in its own parentheses — `([text](url))` — leaves the space
	// where the target was between the text and the closing bracket, so that
	// space goes too.
	return strip_links(s.replace('**', '').replace('__', '').replace('`', ''))
		.replace('[', '')
		.replace(']', '')
		.replace(' )', ')')
}

// strip_links drops a link's target, so the index holds the words a reader sees
// — "see Getting Started" — and not the book's own file names.
fn strip_links(s string) string {
	mut sb := strings.new_builder(s.len + 8)
	mut i := 0
	for i < s.len {
		if s[i] == `]` && i + 1 < s.len && s[i + 1] == `(` {
			mut depth := 1
			i += 2
			for i < s.len && depth > 0 {
				if s[i] == `(` {
					depth++
				} else if s[i] == `)` {
					depth--
				}
				i++
			}
			sb.write_u8(` `)
			continue
		}
		sb.write_u8(s[i])
		i++
	}
	return sb.str()
}

// plain_text is one document's body, used when a page is indexed as a whole.
pub fn plain_text(markdown string) string {
	docs := build_search_docs('', '', '', markdown)
	mut sb := strings.new_builder(512)
	for d in docs {
		sb.write_string(d.text)
		sb.write_string(' ')
	}
	return sb.str().trim_space()
}

// build_search_index serialises the index as a JavaScript file, so the client
// needs no fetch and works from any static host, including file://.
pub fn build_search_index(docs []SearchDoc) string {
	mut sb := strings.new_builder(1024)
	sb.write_string('/* Generated by the site builder. Do not edit. */\n')
	sb.write_string('window.SEARCH_INDEX=[')
	for i, d in docs {
		if i > 0 {
			sb.write_string(',')
		}
		sb.write_string('{"title":')
		sb.write_string(json_string(d.title))
		sb.write_string(',"url":')
		sb.write_string(json_string(d.url))
		sb.write_string(',"text":')
		sb.write_string(json_string(d.text))
		sb.write_string(',"part":')
		sb.write_string(json_string(d.part))
		sb.write_string('}')
	}
	sb.write_string('];\n')
	sb.write_string('window.SEARCH_INDEX_PART=1;\n')
	return sb.str()
}

// json_string quotes a string for JavaScript.
//
// The markup characters are escaped as \u sequences, because the index is
// loaded from a script element where a literal `</` would end the document
// early.
fn json_string(s string) string {
	mut sb := strings.new_builder(s.len + 16)
	sb.write_u8(`"`)
	for c in s {
		match c {
			`"` { sb.write_string('\\"') }
			`\\` { sb.write_string('\\\\') }
			`\n` { sb.write_string('\\n') }
			`\r` { sb.write_string(' ') }
			`\t` { sb.write_string(' ') }
			`<` { sb.write_string('\\u003c') }
			`>` { sb.write_string('\\u003e') }
			`&` { sb.write_string('\\u0026') }
			else { sb.write_u8(u8(c)) }
		}
	}
	sb.write_u8(`"`)
	return sb.str()
}
